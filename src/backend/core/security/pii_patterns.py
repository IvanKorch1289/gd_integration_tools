"""Shared PII regex patterns (S219, S221).

Single source of truth для patterns, которые используются в нескольких
модулях (например, ``core/security/pii_masker.py`` для DSL/audit masking
и ``infrastructure/observability/pii_filter.py`` для structlog masking).

Раньше эти regex были скопированы в оба файла — при изменении формата
(например, добавление нового разделителя в SNILS) легко пропустить одно
из мест. S219 консолидирует SNILS/INN/RU_PASSPORT, S221 — EMAIL/PHONE.

Note: patterns могут быть вынесены в YAML config в будущем (для hot-reload),
сейчас — hardcoded compiled regex (Python compile-once).
"""

from __future__ import annotations

import re
from collections.abc import Callable

__all__ = ("CARD", "EMAIL", "INN", "PHONE", "RU_PASSPORT", "SNILS", "sub_email")


# RU SNILS — ``XXX-XXX-XXX YY`` (с пробелом или без перед последними двумя).
SNILS = re.compile(r"\b\d{3}-\d{3}-\d{3}\s?\d{2}\b")

# INN — 10 (юр.лицо) или 12 (физ.лицо) цифр сплошняком (разделители
# пробелами означают, что это уже не INN, а phone/passport).
INN = re.compile(r"\b\d{12}\b|\b\d{10}\b")

# RU passport — 4 цифры + пробел + 6 цифр (стандартный формат серия+номер).
# Без пробела 10 цифр — это INN, не passport.
RU_PASSPORT = re.compile(r"\b\d{4}\s\d{6}\b")

# S221: Email (RFC 5321-совместимое упрощение).
# Shared between pii_masker и pii_filter (были скопированы с разным escape order).
#
# ADR-0392 (волна 18, кластер G3): прежний вариант
# ``r"[\w.+-]+@[\w-]+\.[\w.-]+"`` давал КВАДРАТИЧНЫЙ бэктрекинг на строках
# без ``@``: ``re.sub`` перебирал каждую стартовую позицию, а ``[\w.+-]+``
# жадно съедал весь остаток строки и откатывался по одному символу
# (10 KB → 238 мс, 50 KB → 6.1 с, 100 KB → 27 с). Любой длинный текст
# без ``@`` (лог, JSON-ответ, тело запроса) блокировал event loop.
#
# Фикс — три ограничения:
#   * квантификаторы ограничены по RFC 5321: local-part ≤ 64, домен ≤ 255,
#     label ≤ 63;
#   * possessiv-группы (``{n,m}+``) запрещают бэктрекинг ВНУТРИ группы —
#     при ошибке движок идёт к следующей стартовой позиции, а не
#     перебирает длины;
#   * домен разложен на label'ы (``(?:\.[\w-]{1,63}+)+``), поэтому длинный
#     хвост не съедается целиком.
#
# Итог: скан линеен по длине входа (100 KB ≈ 30 мс вместо 27 с).
EMAIL = re.compile(r"[\w.+-]{1,64}+@[\w-]{1,255}+(?:\.[\w-]{1,63}+)+")

# S221: Phone — E.164 (+7...) или RU-формат с пробелами/скобками/дефисами.
# Якорь \+ или непрерывная цифровая последовательность ≥ 10.
#
# Leading negative lookahead исключает ISO-8601 дату (``YYYY-MM-DD``, год
# 19xx/20xx). Без него ``[\d\s()\-]{8,}`` съедал любую 10-символьную
# комбинацию цифр и разделителей, поэтому дата в поле ``timestamp`` каждой
# структурированной записи маскировалась: ``2026-09-28T14:39:40Z`` рендерился
# как ``<phone>T14:39:40Z`` — дата терялась во всех логах (невозможно
# упорядочить события по суткам).
#
# Trailing guard ``(?![\d-])`` в lookahead держит fail-closed: если после
# даты идёт продолжение числа (``2026-09-2812``, ``2026-09-28-1234``), это
# уже не дата, и маскирование применяется. Проверено на 19 кейсах: E.164,
# RU-формат со скобками/пробелами, 10 цифр через дефис (``1234-567890``)
# маскируются как раньше.
PHONE = re.compile(r"(?!(?:19|20)\d{2}-\d{2}-\d{2}(?![\d-]))\+?\d[\d\s()\-]{8,}\d")

# S222: Credit card — 13–19 цифр (flexible separators).
# Shared between pii_masker и pii_filter (были скопированы с разным escape).
# ai_sanitizer имеет STRICT 4-4-4-4 regex — намеренно другой semantic,
# оставлен локальным.
CARD = re.compile(r"\b(?:\d[ \-]?){13,19}\b")


def sub_email(repl: str | Callable[[re.Match[str]], str], value: str) -> str:
    """Заменить EMAIL-совпадения в строке (с fast-path для строк без ``@``).

    Используется всеми потребителями, которые маскируют email в
    произвольном тексте (ответы middleware, тела запросов в логах).
    Прямой вызов ``EMAIL.sub(...)`` остаётся доступен, но требует
    предварительной проверки ``"@" in value`` — иначе на длинных строках
    без ``@`` платится полный скан (ADR-0392).

    Args:
        repl: Замена — строка или callable (как в :func:`re.sub`).
        value: Исходная строка.

    Returns:
        Строка с заменёнными email-совпадениями. Если в ``value`` нет
        ``@`` — возвращается исходная строка без изменений.

    """
    if "@" not in value:
        # Email без ``@`` невозможен — regex не запускаем вовсе.
        return value
    return EMAIL.sub(repl, value)
